import type { SVGProps } from 'react';

/**
 * The Vora icon set. Two families, both drawn for the redesigned shell:
 *  - Line icons on a 24 grid with a 1.6 stroke, used for navigation. Pass `active` to fill them with
 *    the brand tint (the mockup's active nav state).
 *  - Solid utility icons on a 256 grid (search, chevrons, arrows, bell...), and a few duotone ones
 *    for list rows. These inherit `currentColor`.
 */
export type VoraIconProps = Omit<SVGProps<SVGSVGElement>, 'children'> & { size?: number; active?: boolean };
export type VoraIcon = (props: VoraIconProps) => React.JSX.Element;

function line(d: string | string[]): VoraIcon {
    const paths = Array.isArray(d) ? d : [d];
    function LineIcon({ size = 17, active = false, strokeWidth, style, ...rest }: VoraIconProps) {
        return (
            <svg
                width={size}
                height={size}
                viewBox="0 0 24 24"
                fill={active ? 'var(--brand-fill, rgba(24,24,27,0.1))' : 'none'}
                stroke={active ? 'var(--brand-ink, var(--brand, currentColor))' : 'currentColor'}
                strokeWidth={strokeWidth ?? (active ? 1.75 : 1.6)}
                strokeLinecap="round"
                strokeLinejoin="round"
                aria-hidden
                style={{ flexShrink: 0, ...style }}
                {...rest}
            >
                {paths.map((p) => (
                    <path key={p} d={p} />
                ))}
            </svg>
        );
    }
    return LineIcon;
}

function solid(d: string, duotone?: string): VoraIcon {
    function SolidIcon({ size = 16, active: _active, style, ...rest }: VoraIconProps) {
        void _active;
        return (
            <svg width={size} height={size} viewBox="0 0 256 256" fill="currentColor" aria-hidden style={{ flexShrink: 0, ...style }} {...rest}>
                {duotone && <path d={duotone} opacity={0.2} />}
                <path d={d} />
            </svg>
        );
    }
    return SolidIcon;
}

